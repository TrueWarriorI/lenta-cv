"""
config.py — Единый конфиг всего проекта
========================================
Все настройки в одном месте. Меняй здесь — изменится везде.

Импорт в других модулях:
    from config import LOADER_CONFIG, DETECTOR_CONFIG, OCR_CONFIG
"""

from video_loader import VideoLoaderConfig
from detector import DetectorConfig
from preprocessor import PreprocessorConfig
from ocr_engine import OCRConfig
from tracker import TrackerConfig


# ═══════════════════════════════════════════════
# ГЛАВА 1 — Загрузка и предобработка видео
# ═══════════════════════════════════════════════

LOADER_CONFIG = VideoLoaderConfig(

    # Сколько кадров в секунду брать из видео.
    # 2.0 — хороший баланс скорость/покрытие для робота с остановками.
    # 5.0 — для видео без остановок (непрерывное движение).
    fps_sample=2.0,

    # Фильтр дублирующихся кадров.
    # 0.02 = пропускаем кадр если изменилось менее 2% пикселей.
    # Уменьши до 0.01 если теряются кадры при медленном движении.
    # Увеличь до 0.05 если слишком много похожих кадров проходит.
    diff_threshold=0.02,

    # CLAHE — адаптивное улучшение контраста.
    # Рекомендуется держать True: помогает при смешанном освещении магазина.
    apply_clahe=True,

    # Fisheye-коррекция.
    # True если на кадрах видно сильное искажение по краям (как на скриншотах).
    # False если камера прямая или коррекция уже применена в самом роботе.
    apply_undistort=False,

    # Масштаб кадра перед обработкой.
    # 1.0 = оригинальный размер (рекомендуется для OCR).
    # 0.5 = ускоряет в 4 раза, но ухудшает читаемость мелкого текста.
    scale=1.0,

    # Шумоподавление (bilateral filter).
    # 3 = лёгкое, почти незаметное.
    # 5 = среднее, может чуть смазать мелкий текст.
    # 0 = выключено.
    # При 4K видео шумоподавление не нужно — только размывает текст
    denoise_ksize=0,
)


# ═══════════════════════════════════════════════
# ГЛАВА 2 — Детекция ценников (заполним позже)
# ═══════════════════════════════════════════════

DETECTOR_CONFIG = DetectorConfig(

    # Путь к весам YOLOv8.
    # None = использовать стандартный yolov8n.pt
    # После обучения — укажи путь к дообученной модели:
    # model_path="trained_models/lenta_price_tags/weights/best.pt",
    model_path="runs/detect/trained_models/lenta_price_tags/weights/best.pt",

    # Порог уверенности YOLO
    confidence=0.35,
    iou_threshold=0.45,

    # HSV как дополнение к YOLO
    use_hsv_fallback=True,
    hsv_only=False,

    # ── Фильтры размера ──────────────────────────────────────────────────
    # Ценники крепятся ВЕРТИКАЛЬНО на боковых разделителях полок.
    # На разрешении ~1456x816: ширина ~30-60px, высота ~100-200px.
    min_width=25,
    min_height=60,

    # Максимум — отсекаем случайные крупные объекты
    max_width=200,
    max_height=500,

    # Ценники ВЕРТИКАЛЬНЫЕ: aspect = width/height обычно 0.15..0.6
    # Допускаем до 3.0 для других зон магазина где ценники горизонтальные.
    min_aspect_ratio=0.1,
    max_aspect_ratio=3.0,


    # NMS порог для финального объединения YOLO + HSV результатов
    final_iou_threshold=0.4,
)


# ═══════════════════════════════════════════════
# ГЛАВА 3 — Предобработка кропов
# ═══════════════════════════════════════════════

PREPROCESSOR_CONFIG = PreprocessorConfig(

    # Отступ вокруг bbox детектора в пикселях.
    # 8px — чтобы не срезать края ценника если bbox чуть промахнулся.
    # Большой padding снизу — ценник часто выступает ниже bbox детектора
    padding=15,
    padding_bottom_extra=40,  # дополнительный отступ снизу

    # Минимальный размер кропа подаваемого в OCR.
    # Если ценник меньше — апскейлим до этого размера (INTER_CUBIC).
    min_ocr_width=200,
    min_ocr_height=80,

    # Максимальный размер — ограничиваем чтобы OCR не тормозил.
    max_ocr_width=1200,
    max_ocr_height=600,

    # Автоматическая коррекция перспективы (ценники под углом из-за fisheye).
    # Работает через поиск 4 углов ценника внутри кропа.
    # Отключи если даёт артефакты (проверь в debug_crops/).
    apply_perspective=True,

    # CLAHE на кропе — улучшает контраст текста при неравномерном освещении.
    apply_clahe=True,

    # Unsharp mask — повышает резкость текста после апскейла.
    # При 4K sharpen не нужен — добавляет артефакты на чётком изображении
    apply_sharpen=False,

    # Сохранять кропы в debug_crops/ для ручной проверки.
    # Включай когда нужно проверить качество предобработки.
    debug_save=False,
    debug_dir="debug_crops",
)


# ═══════════════════════════════════════════════
# ГЛАВА 4 — OCR и распознавание кодов
# ═══════════════════════════════════════════════

OCR_CONFIG = OCRConfig(

    # Язык OCR. "ru" = русский + английский цифры.
    # "ch" — мультиязычная модель, лучше читает смешанный текст
    # (кириллица + латиница + цифры на ценниках Ленты)
    lang="ch",

    # GPU ускорение. False = CPU (достаточно для нашей задачи).
    # Если есть CUDA-совместимая карта — поставь True для скорости.
    use_gpu=False,

    # Классификатор угла текста — критично для повёрнутых ценников.
    # Ценники на видео стоят вертикально → обязательно True.
    use_angle_cls=True,

    # Минимальная уверенность OCR. Блоки ниже порога игнорируются.
    # 0.5 = отсекаем явный мусор, но берём сложные случаи.
    min_confidence=0.5,

    # Количество попыток чтения штрихкода:
    # 1 = только исходный, 2 = + увеличенный, 3 = + инвертированный
    barcode_attempts=3,
)


